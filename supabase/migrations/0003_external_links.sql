-- بوابة دفعة 32 — روابط خارجية اختيارية للملفات والملخصات
-- يسمح لكل ملف/ملخص إما برفعه مباشرة (Supabase Storage) أو بربطه برابط
-- خارجي (قوقل درايف مثلًا) — مفيد للملفات الكبيرة (فيديوهات المحاضرات)
-- اللي ممكن تستهلك حصة التخزين المجانية بسرعة.
-- =========================================================================

alter table public.subject_files
  add column if not exists external_url text,
  alter column storage_path drop not null;

alter table public.summaries
  add column if not exists external_url text;
-- storage_path في جدول summaries كان أصلًا nullable من البداية.

-- ملاحظة: التحقق من "لازم يكون فيه رابط أو ملف" يتم من واجهة الإدارة نفسها،
-- مو عبر قيد صارم في قاعدة البيانات، عشان نتجنب تعقيد الترحيل.
